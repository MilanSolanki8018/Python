# Membership Function : in & not in

list1=[10,20,30,40,50]
tuple1=(1,2,3,4,5)
str1="Welcome"

print(40 in list1)
print(60 in list1)
print(60 not in list1)

print()

print(6 in tuple1)
print(8 not in tuple1)

print()

print('c' in str1)
print('p' not in str1)

print()

if(80 in list1):
    print("80 is available")
else:
    print("80 is not available")
